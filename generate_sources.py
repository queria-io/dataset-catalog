"""Auto-generate catalog dbt raw models from datasources.yml.

Generated files:
  - models/main/raw/raw_{name}_manifest.sql (per datasource)
  - models/main/raw/raw_{name}_catalog.sql (per datasource)
  - models/main/raw/raw_{name}_meta.sql (per datasource)
  - models/main/raw/_schema.yml
  - models/main/stg/stg_all_manifests.sql (UNION ALL)
  - models/main/stg/stg_all_catalogs.sql (UNION ALL)
  - models/main/stg/stg_all_metas.sql (UNION ALL)

Also generates:
  - .queria/artifacts/{name}_meta.json (dataset.json または fdl.toml から変換)
"""

from __future__ import annotations

import json
import os
import sys
import tomllib
from pathlib import Path

import yaml

CATALOG_DIR = Path(__file__).resolve().parent
DATASOURCES_YML = CATALOG_DIR / "datasources.yml"
RAW_DIR = CATALOG_DIR / "models" / "main" / "raw"
STG_DIR = CATALOG_DIR / "models" / "main" / "stg"
ARTIFACTS_DIR = CATALOG_DIR / ".queria" / "artifacts"

GENERATED_HEADER = "-- Auto-generated by generate_sources.py. Do not edit manually."


def load_datasources() -> list[dict]:
    with open(DATASOURCES_YML) as f:
        return yaml.safe_load(f)["datasources"]


#: Where the datasets are published. **Read every other dataset through this,
#: not through the bucket**, because the datasets are moving one at a time from
#: `{name}/...` to `queria/{name}/...` and only the delivery host knows which
#: have moved: it answers the same URL from whichever key the dataset is at
#: today. Reading the bucket directly means reading whatever the last fdl push
#: left at the old key, which for a migrated dataset is frozen and looks fine.
PUBLIC_URL = "https://data.queria.io"


def storage_base() -> str:
    """Where to read the other datasets from: the delivery host, always.

    There is no local variant any more. fdl could be pointed at a directory,
    and this had a branch for reading the other datasets out of it; queria
    always writes to the dataset's own storage, so the only place the others
    can be read from is where they are published.
    """
    if not os.environ.get("QUERIA_DATA_URL"):
        raise SystemExit(
            "QUERIA_DATA_URL is not set. Run this through `queria run` "
            "(scripts/build.sh does)."
        )
    return os.environ.get("QUERIA_PUBLIC_URL", PUBLIC_URL).rstrip("/")


#: Sent on every fetch. Cloudflare sits in front of the delivery host and bans
#: the User-Agent urllib sends by default (`Python-urllib/3.x`) by signature:
#: the reply is `error code: 1010`, not a rate limit, so retrying never helps
#: and a build that does not name itself reads nothing at all.
#:
#: Named the way everything else here names itself (`queria-cli/{version}`,
#: `queria-dataset-edinet/1.0`). No `(+url)`: that is for telling a stranger's
#: site who is crawling it, and this only ever calls Queria's own delivery.
USER_AGENT = "queria-catalog/1.0"


def http_get(url: str) -> bytes | None:
    """Fetch an object from the delivery host. None if it is not there."""
    import urllib.error
    import urllib.request

    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            return response.read()
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            return None
        raise


def meta_from_declaration(declaration: dict, name: str, public_url: str) -> dict:
    """Map a published dataset.json onto the shape the meta models read.

    The declaration renamed most of what fdl.toml called these things, so the
    mapping is spelled out rather than merged: keywords were tags, homepage was
    repository_url, update_frequency was schedule, and the single license and
    source became lists. Only the first of each list survives here, because
    that is all the catalog has a column for.

    ai_context has no counterpart in fdl.toml. It is the one field a publisher
    can write prose in that is meant for agents rather than for the catalog UI,
    and until now nothing read it back out.
    """
    licenses = declaration.get("licenses") or [{}]
    sources = declaration.get("sources") or [{}]
    return {
        "datasource": name,
        "title": declaration.get("title") or "",
        "description": declaration.get("description") or "",
        "cover": declaration.get("cover") or "",
        "tags": declaration.get("keywords") or [],
        "repository_url": declaration.get("homepage") or "",
        "schedule": declaration.get("update_frequency") or "",
        "license": licenses[0].get("title") or "",
        "license_url": licenses[0].get("url") or "",
        "source_url": sources[0].get("path") or "",
        "ducklake_url": f"{public_url}/{name}/ducklake.duckdb",
        # fdl.toml held this as {name: {title, ...}}; the declaration lists it.
        "schemas": {
            s["name"]: {k: v for k, v in s.items() if k != "name"}
            for s in (declaration.get("schemas") or [])
            if s.get("name")
        },
        "ai_context": declaration.get("ai_context"),
    }


def meta_from_fdl_toml(config: dict, name: str) -> dict:
    """Map a published fdl.toml onto the same shape."""
    meta = config.get("meta", {})
    target = config.get("targets", {}).get("default", {})
    public_url = target.get("public_url", PUBLIC_URL)

    return {
        "datasource": name,
        "title": meta.get("title", ""),
        "description": meta.get("description", ""),
        "cover": meta.get("cover", ""),
        "tags": meta.get("tags", []),
        "repository_url": meta.get("repository_url", ""),
        "schedule": meta.get("schedule", ""),
        "license": meta.get("license", ""),
        "license_url": meta.get("license_url", ""),
        "source_url": meta.get("source_url", ""),
        "ducklake_url": f"{public_url}/{name}/ducklake.duckdb",
        "schemas": meta.get("schemas", {}),
        # fdl.toml has nothing to put here. Written anyway so every artifact
        # has the same keys and read_json does not have to guess.
        "ai_context": None,
    }


def generate_meta_jsons(datasources: list[dict], base_url: str) -> None:
    """Write one meta JSON per datasource, from whichever metadata it publishes.

    dataset.json is what a dataset publishes once it has moved to declarations,
    and it is the only one of the two that is still being written. fdl.toml is
    what the rest published before the migration; nothing updates those any
    more, and the gateway serves them for as long as this reads them
    (contract: "fdl.toml は配信し続ける").

    So the declaration wins where there is one. Reading fdl.toml for a migrated
    dataset would show whatever its metadata said on the day it stopped being
    the source of truth.
    """
    ARTIFACTS_DIR.mkdir(parents=True, exist_ok=True)

    for ds in datasources:
        name = ds["name"]

        raw = http_get(f"{base_url}/{name}/dataset.json")
        if raw:
            out = meta_from_declaration(json.loads(raw.decode()), name, base_url)
            print(f"  {name}: dataset.json")
        else:
            raw = http_get(f"{base_url}/{name}/fdl.toml")
            if not raw:
                print(
                    f"  {name}: neither dataset.json nor fdl.toml at "
                    f"{base_url}/{name}/, skipping"
                )
                continue
            out = meta_from_fdl_toml(tomllib.loads(raw.decode()), name)
            print(f"  {name}: fdl.toml (not migrated to a declaration yet)")

        out_path = ARTIFACTS_DIR / f"{name}_meta.json"
        with open(out_path, "w") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)


def generate_raw_sql(name: str, macro: str) -> str:
    return f"{GENERATED_HEADER}\n{{{{ {macro}('{name}') }}}}\n"


def generate_union_all(datasources: list[dict], suffix: str) -> str:
    lines = [GENERATED_HEADER, "{{ config(materialized='view') }}", ""]
    for i, ds in enumerate(datasources):
        if i > 0:
            lines.append("UNION ALL")
        lines.append(f"SELECT * FROM {{{{ ref('raw_{ds['name']}_{suffix}') }}}}")
    lines.append("")
    return "\n".join(lines)


def generate_schema_yml(datasources: list[dict]) -> str:
    models = []
    for ds in datasources:
        for suffix, label in [
            ("manifest", "manifest"),
            ("catalog", "catalog"),
            ("meta", "メタデータ"),
        ]:
            models.append({
                "name": f"raw_{ds['name']}_{suffix}",
                "description": f"{ds['description']} ({label})",
            })
    schema = {"version": 2, "models": models}
    header = "# Auto-generated by generate_sources.py. Do not edit manually.\n"
    return header + yaml.dump(schema, default_flow_style=False, allow_unicode=True, sort_keys=False)


def warn_stale_files(datasources: list[dict]) -> None:
    # The .table.yml next to each raw model is the dataset declaration. This
    # script does not write those -- they are edited by hand -- but they belong
    # to the same datasource, so they are expected here too. Leaving them out
    # reported every one of them as stale and buried the real warnings.
    expected = {"_schema.yml"}
    for ds in datasources:
        for suffix in ["manifest", "catalog", "meta"]:
            expected.add(f"raw_{ds['name']}_{suffix}.sql")
            expected.add(f"raw_{ds['name']}_{suffix}.table.yml")
    for path in RAW_DIR.iterdir():
        if path.name.startswith("."):
            continue
        if path.name not in expected:
            print(f"WARNING: stale file found: {path.relative_to(CATALOG_DIR)}", file=sys.stderr)


def main() -> None:
    datasources = load_datasources()
    RAW_DIR.mkdir(parents=True, exist_ok=True)
    STG_DIR.mkdir(parents=True, exist_ok=True)

    base_url = storage_base()

    # Set QUERIA_STORAGE_BASE for dbt macros (read_dataset_manifest/catalog)
    os.environ["QUERIA_STORAGE_BASE"] = base_url

    # Convert fdl.toml → JSON (generates .queria/artifacts/{name}_meta.json)
    generate_meta_jsons(datasources, base_url)

    # Generate per-datasource raw models
    for ds in datasources:
        name = ds["name"]
        for suffix, macro in [
            ("manifest", "read_dataset_manifest"),
            ("catalog", "read_dataset_catalog"),
            ("meta", "read_dataset_meta"),
        ]:
            out = RAW_DIR / f"raw_{name}_{suffix}.sql"
            out.write_text(generate_raw_sql(name, macro))
            print(f"  generated: {out.relative_to(CATALOG_DIR)}")

    # Generate UNION ALL stg models
    for suffix in ["manifest", "catalog", "meta"]:
        path = STG_DIR / f"stg_all_{suffix}s.sql"
        path.write_text(generate_union_all(datasources, suffix))
        print(f"  generated: {path.relative_to(CATALOG_DIR)}")

    # Schema
    schema_path = RAW_DIR / "_schema.yml"
    schema_path.write_text(generate_schema_yml(datasources))
    print(f"  generated: {schema_path.relative_to(CATALOG_DIR)}")

    warn_stale_files(datasources)
    print("done.")


if __name__ == "__main__":
    main()
